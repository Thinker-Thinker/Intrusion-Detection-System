"""
Turn one TinyEngine gen dir into firmware files that can sit next to other models in the same build.

    python te_namespace.py <gen_dir> <prefix> <out_dir> --arena-offset N [--extflash]

* <prefix>_model.c / <prefix>_model.h: every model function gets the prefix (det_invoke, det_getInput, ...),
  file-scope variables and weight tables become static (no clashes between models);
* the activation arena is not a private array any more: it is axi_pool + N (one 320 KB AXI SRAM pool shared
  by the camera frame and all models, which run one at a time);
* the im2col/kernel scratch buffers point to te_sbuf / te_kbuf (shared, in D3 / D2 SRAM);
* --extflash puts the weight tables in section .extflash (external OSPI flash, memory mapped at 0x90000000);
* kernel sources generated for the model are copied to <out_dir>/kernels (identical names = identical files).
"""
import argparse, re, shutil, filecmp
from pathlib import Path
ap = argparse.ArgumentParser()
ap.add_argument("gen"); ap.add_argument("prefix"); ap.add_argument("out"); ap.add_argument("--arena-offset", type=int, required=True)
ap.add_argument("--extflash", action="store_true")
a = ap.parse_args()
g, p, out = Path(a.gen) / "codegen", a.prefix, Path(a.out); out.mkdir(parents=True, exist_ok=True)

h = (g / "Include/genModel.h").read_text()
m = re.search(r"static signed char buffer\[(\d+)\];", h); total = int(m.group(1))
sb = int(re.search(r"static int16_t \*sbuf = \(int16_t \*\)&buffer\[(\d+)\];", h).group(1))
kb = int(re.search(r"static int16_t \*kbuf = \(int16_t \*\)&buffer\[(\d+)\];", h).group(1))
h = h.replace(m.group(0), f"extern signed char axi_pool[];\n#define buffer (axi_pool + {a.arena_offset})  /* activations: {sb} bytes */")
h = re.sub(r"static int16_t \*sbuf = \(int16_t \*\)&buffer\[\d+\];", "extern int16_t te_sbuf[]; static int16_t *sbuf = te_sbuf;", h)
h = re.sub(r"static int16_t \*kbuf = \(int16_t \*\)&buffer\[\d+\];", "extern int16_t te_kbuf[]; static int16_t *kbuf = te_kbuf;", h)
h = re.sub(r"^const int (SBuffer_size|KBuffer_size)", r"static const int \1", h, flags=re.M)
attr = '__attribute__((section(".extflash"), aligned(4))) ' if a.extflash else ""
h, n = re.subn(r"^const (unsigned char|int32_t|float|int8_t|int16_t|uint8_t) ", lambda mm: f"static {attr}const {mm.group(1)} ", h, flags=re.M)
h = h.replace("#define PEAK_MEM", f"#define {p.upper()}_PEAK_MEM").replace("#define MODEL_SIZE", f"#define {p.upper()}_MODEL_SIZE")
(out / f"{p}_model.h").write_text(f"/* Generated by te_namespace.py from TinyEngine output - do not edit. */\n" + h)

c = (g / "Source/genModel.c").read_text()
c = c.replace('#include "genModel.h"', f'#include "{p}_model.h"')
c = re.sub(r"^(ADD_params add_params;|int i;|int8_t \*int8ptr,\*int8ptr2;|int32_t \*int32ptr;|float \*fptr,\*fptr2,\*fptr3;)",
           r"static \1", c, flags=re.M)
for fn in ("getInput", "getOutput", "end2endinference", "invoke_inf", "invoke", "te_model_arena"):
    c = re.sub(rf"\b{fn}\(", f"{p}_{fn}(", c)
(out / f"{p}_model.c").write_text(c)
if (g / "Include/heads.h").exists(): shutil.copy(g / "Include/heads.h", out / f"{p}_heads.h")

kd = out / "kernels"; kd.mkdir(exist_ok=True)
for f in (g / "Source").glob("*.c"):
    if f.name == "genModel.c": continue
    dst = kd / f.name
    if dst.exists() and not filecmp.cmp(f, dst, shallow=False):
        raise SystemExit(f"kernel {f.name} differs between models")
    shutil.copy(f, dst)
print(f"{p}: {n} weight tables{' in .extflash' if a.extflash else ''}, activations {sb} B at axi_pool+{a.arena_offset}, "
      f"sbuf {kb - sb} B, kbuf {total - kb} B")
