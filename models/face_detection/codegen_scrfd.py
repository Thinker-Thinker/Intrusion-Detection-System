"""
TinyEngine code generation for the SCRFD-500M detector, keeping all 9 head outputs.

TinyEngine's normal code exposes one output and reuses the memory of every other tensor. The detector has
9 outputs (score / box / keypoints at strides 8, 16, 32), so this script pins those 9 tensors to the end of
the run (via TinyEngine's outputTables lifetime mechanism) and writes scrfd_heads.h with the address,
shape and int8 quantisation of each head inside the TinyEngine arena.

    python codegen_scrfd.py scrfd_160x128_int8.tflite --tinyengine <tinyengine clone> --out gen_scrfd
"""
import argparse, os, sys
from pathlib import Path

ap = argparse.ArgumentParser()
ap.add_argument("tflite"); ap.add_argument("--tinyengine", required=True); ap.add_argument("--out", default="gen_scrfd")
a = ap.parse_args()
tflite = str(Path(a.tflite).resolve()); sys.path.insert(0, str(Path(a.tinyengine).resolve()))
out = Path(a.out).resolve(); out.mkdir(parents=True, exist_ok=True); os.chdir(out)

from code_generator.TfliteConvertor import TfliteConvertor
from code_generator.GeneralMemoryScheduler import GeneralMemoryScheduler
from code_generator.CodeGenerator import CodeGenerator
from code_generator.TTEParser import outputInfo

tc = TfliteConvertor(tflite); tc.parseOperatorInfo(); L = tc.layer

# TinyEngine runs every int8 depthwise layer in place (output written over its input). SCRFD's feature pyramid
# reads some of those inputs again later (lateral branches), so copy such inputs first and point the other
# readers at the copy. The copy is an upsample with factor 1 (a plain memory copy in TinyEngine).
from code_generator.operators.upsample import upSample
i = 0
while i < len(L):
    l = L[i]
    if l.params["op"] == "DEPTHWISE_CONV_2D" and l.params.get("input_dtype", "int8") == "int8":
        g = str(l.input_tensors[0].graph_idx)
        others = [m for m in L if m is not l and any(str(t.graph_idx) == g for t in m.input_tensors)]
        if others:
            p = l.params; cid = f"{g}_copy"
            cp = upSample({"input_idx": g, "output_idx": cid, "factor": 1, "input_dim": 3, "output_dim": 3,
                           "input_h": p["input_h"], "input_w": p["input_w"], "input_c": p["input_c"],
                           "output_h": p["input_h"], "output_w": p["input_w"], "output_c": p["input_c"]})
            for m in others:
                for t in m.input_tensors:
                    if str(t.graph_idx) == g: t.graph_idx = cid
                for k in ("input_idx", "input2_idx", "input1_idx"):
                    if str(m.params.get(k)) == g: m.params[k] = cid
            L.insert(i, cp); i += 1
            print(f"copy inserted before depthwise #{i}: {p['input_h']}x{p['input_w']}x{p['input_c']} read again by {len(others)} layer(s)")
    i += 1
consumed = {str(t.graph_idx) for l in L for t in l.input_tensors}
heads = [l for l in L if str(l.output_tensors[0].graph_idx) not in consumed]
assert len(heads) == 9, f"expected 9 head outputs, found {len(heads)}"
pins = [outputInfo(f"scrfd_head_{h.output_tensors[0].graph_idx}", str(h.output_tensors[0].graph_idx),
                   h.output_tensors[0].len(), "int8") for h in heads]

ms = GeneralMemoryScheduler(L, False, False, outputTables=pins, inplace=True,
                            mem_visual_path=str(out / "lifecycle.png"), VisaulizeTrainable=False)
ms.USE_INPLACE = True; ms.allocateMemory()
CodeGenerator(memsche=ms, inplace=True, unsigned_input=False, patch_params=None, FP_output=False, profile_mode=False,
              fp_requantize=True, tflite_op=False, dummy_address=False, outputTables=pins).codeGeneration()

# TinyEngine maps every 3x3 stride-2 conv to a kernel that only supports 3 input channels; route the others
# to convolve_s8_kernel3_stride2_pad1_fpreq_any (firmware/stm32h723/tinyengine_extra).
import re
gm = out / "codegen/Source/genModel.c"; src = gm.read_text()
src, n = re.subn(r"convolve_s8_kernel3_inputch3_stride2_pad1_fpreq\((&buffer0\[\d+\]),(\d+),(\d+),(\d+),",
                 lambda m: (m.group(0) if m.group(4) == "3" else
                            f"convolve_s8_kernel3_stride2_pad1_fpreq_any({m.group(1)},{m.group(2)},{m.group(3)},{m.group(4)},"), src)
src += "\nsigned char *scrfd_arena(void) { return buffer0; }\n"
gm.write_text(src)
print("stride-2 3x3 convs rerouted:", src.count("convolve_s8_kernel3_stride2_pad1_fpreq_any(") // 2)

rows = []
for h in heads:
    p = h.params; t = h.output_tensors[0]
    addr = h._getBufferstr(p["output_buf_add"], p["output_buf_add_offset"])
    stride = 128 // p["output_h"]; kind = {2: "SCORE", 8: "BOX", 20: "KPS"}[p["output_c"]]
    rows.append((stride, kind, addr, p["output_h"], p["output_w"], p["output_c"], float(p["output_scale"]), int(p["output_zero_point"])))
rows.sort()
with open(out / "codegen/Include/scrfd_heads.h", "w") as f:
    f.write("/* Generated by codegen_scrfd.py: where each SCRFD head output sits in the TinyEngine arena (HWC int8). */\n")
    f.write("#ifndef SCRFD_HEADS_H\n#define SCRFD_HEADS_H\n#include <stdint.h>\n")
    f.write("typedef struct { int stride; int kind; const int8_t *data; int h, w, c; float scale; int zero_point; } scrfd_head_t;\n")
    f.write("enum { SCRFD_SCORE = 0, SCRFD_BOX = 1, SCRFD_KPS = 2 };\n")
    f.write("extern signed char *scrfd_arena(void);\n")
    f.write("#define SCRFD_HEADS(buffer0) { \\\n")
    for st, kind, addr, hh, ww, cc, sc, zp in rows:
        f.write(f"    {{{st}, SCRFD_{kind}, (const int8_t *){addr}, {hh}, {ww}, {cc}, {sc:.9g}f, {zp}}}, \\\n")
    f.write("}\n#endif\n")
    print(open(out / "codegen/Include/scrfd_heads.h").read())
print(f"arena: {ms.buffers['input_output']/1024:.1f} KB (+ im2col/kernel buffers)")
